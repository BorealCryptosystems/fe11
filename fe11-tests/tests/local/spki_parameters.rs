#[test]
fn spki_size() {
    assert!(AgreementPeer::from_spki(AgreementCurve::P256, VALID_P256).is_ok());
    let malformed = &[];
    let actual = AgreementPeer::from_spki(AgreementCurve::P256, malformed);
    assert!(matches!(actual, Err(Error::Rejected(RejectionReason::ClassicalSignatures(
        ClassicalSignaturesRejection::SpkiSize
    )))));
    assert!(AgreementPeer::from_spki(AgreementCurve::P256, VALID_P256).is_ok());
}

