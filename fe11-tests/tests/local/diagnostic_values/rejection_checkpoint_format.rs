//! Public CheckpointFormatRejection values retain identity through category conversion.
use fe11::{CheckpointFormatRejection, Error, RejectionReason};

#[test]
fn variants_preserve_category_and_payload() {
    let cases = [
        CheckpointFormatRejection::CallerFedAeadAsynchronousModeUnavailable,
        CheckpointFormatRejection::CheckpointSymmetricProfile,
        CheckpointFormatRejection::CipherGraphOnAnotherRecordFamily,
        CheckpointFormatRejection::CipherOptionsOnAnotherRecordFamily,
        CheckpointFormatRejection::DetachedActiveMessageAbsent,
        CheckpointFormatRejection::DetachedCryptographicFamily,
        CheckpointFormatRejection::DetachedInputLength,
        CheckpointFormatRejection::DetachedMessageAbsent,
        CheckpointFormatRejection::DetachedOutputCapacity,
        CheckpointFormatRejection::DetachedOutputCeiling,
        CheckpointFormatRejection::DetachedOutputProgression,
        CheckpointFormatRejection::DigestOidOnANonDigestRecord,
        CheckpointFormatRejection::DigestExtensionOnAnotherFamily,
        CheckpointFormatRejection::DigestOutputOnAnotherFamily,
        CheckpointFormatRejection::DigestOutputStorageAbsent,
        CheckpointFormatRejection::DigestOutputStorageLimit,
        CheckpointFormatRejection::DigestOutputWaitIsNotARetainedTerminal,
        CheckpointFormatRejection::DigestParametersOnAnotherRecordFamily,
        CheckpointFormatRejection::NativeBlockCipherAsynchronousModeUnavailable,
        CheckpointFormatRejection::NativeSignatureValidationDispatch,
        CheckpointFormatRejection::RecordAeadOutput,
        CheckpointFormatRejection::RecordAeadParameterSelection,
        CheckpointFormatRejection::RecordAesProfile,
        CheckpointFormatRejection::RecordCcmMacAlignment,
        CheckpointFormatRejection::RecordCcmFixedBits,
        CheckpointFormatRejection::RecordCcmGenerator,
        CheckpointFormatRejection::RecordCcmInitialNonce,
        CheckpointFormatRejection::RecordCtrCounterWidthAbsent,
        CheckpointFormatRejection::RecordIvFixedBitsAbsent,
        CheckpointFormatRejection::RecordIvGeneratorAbsent,
        CheckpointFormatRejection::RecordInitLayoutForANonAeadMessageFamily,
        CheckpointFormatRejection::RecordMacKey,
        CheckpointFormatRejection::RecordMacProfile,
        CheckpointFormatRejection::RecordRsaProfile,
        CheckpointFormatRejection::RecordActiveMessagePhase,
        CheckpointFormatRejection::RecordBatchFinalPhase,
        CheckpointFormatRejection::RecordBufferedMessageInputState,
        CheckpointFormatRejection::RecordCarriedMessageUnfinished,
        CheckpointFormatRejection::RecordCarriedPrefix,
        CheckpointFormatRejection::RecordCarriedPrefixWidth,
        CheckpointFormatRejection::RecordCipherInitProgression,
        CheckpointFormatRejection::RecordCipherMechanism,
        CheckpointFormatRejection::RecordCipherNonce,
        CheckpointFormatRejection::RecordCipherObservationAssociation,
        CheckpointFormatRejection::RecordCipherParameters,
        CheckpointFormatRejection::RecordClassicBatch,
        CheckpointFormatRejection::RecordConsumedLength,
        CheckpointFormatRejection::RecordCounterWidthOnNonCtrOperation,
        CheckpointFormatRejection::RecordDescriptorFlags,
        CheckpointFormatRejection::RecordDigestParameters,
        CheckpointFormatRejection::RecordDigestPhase,
        CheckpointFormatRejection::RecordDualMacClass,
        CheckpointFormatRejection::RecordDualActiveState,
        CheckpointFormatRejection::RecordDualCapacity,
        CheckpointFormatRejection::RecordDualPhase,
        CheckpointFormatRejection::RecordEmptyOperation,
        CheckpointFormatRejection::RecordExpectedMac,
        CheckpointFormatRejection::RecordFinalProgression,
        CheckpointFormatRejection::RecordFinalizedCipherLength,
        CheckpointFormatRejection::RecordInactiveClassicOperation,
        CheckpointFormatRejection::RecordInitialIvAbsent,
        CheckpointFormatRejection::RecordInitialProgression,
        CheckpointFormatRejection::RecordInputLength,
        CheckpointFormatRejection::RecordMessageByteCounter,
        CheckpointFormatRejection::RecordMessageObservationAssociation,
        CheckpointFormatRejection::RecordMessageOutputCounter,
        CheckpointFormatRejection::RecordMessagePhase,
        CheckpointFormatRejection::RecordMessageProgressMismatch,
        CheckpointFormatRejection::RecordMessageSubmissionCounter,
        CheckpointFormatRejection::RecordMessageSubmissionWidth,
        CheckpointFormatRejection::RecordMissingCipherObservation,
        CheckpointFormatRejection::RecordMissingMessageObservation,
        CheckpointFormatRejection::RecordMixedRoutes,
        CheckpointFormatRejection::RecordNativeAeadKeyProfile,
        CheckpointFormatRejection::RecordNonAeadNonceSelection,
        CheckpointFormatRejection::RecordOperationFamily,
        CheckpointFormatRejection::RecordOutputPrecedesInput,
        CheckpointFormatRejection::RecordPrematureDualAuthentication,
        CheckpointFormatRejection::RecordPrematureSignature,
        CheckpointFormatRejection::RecordProfileKeyRoles,
        CheckpointFormatRejection::RecordRequiredValidationAbsent,
        CheckpointFormatRejection::RecordRetainedMessageSubmission,
        CheckpointFormatRejection::RecordSignatureAssociation,
        CheckpointFormatRejection::RecordSignatureCapacity,
        CheckpointFormatRejection::RecordSignatureParameterFamily,
        CheckpointFormatRejection::RecordSignatureParameters,
        CheckpointFormatRejection::RecordSignatureResult,
        CheckpointFormatRejection::RecordSingleDigestProgression,
        CheckpointFormatRejection::RecordSingleMessageProgress,
        CheckpointFormatRejection::RecordStreamAeadKeyProfile,
        CheckpointFormatRejection::RecordStreamAeadNonce,
        CheckpointFormatRejection::RecordStreamAeadParameters,
        CheckpointFormatRejection::RecordTokenIvDirection,
        CheckpointFormatRejection::RecordUnexpectedResidual,
        CheckpointFormatRejection::RecordUnexpectedValidationObservation,
        CheckpointFormatRejection::RecordUpdateProgression,
        CheckpointFormatRejection::RecordValidationCapacity,
        CheckpointFormatRejection::RecordValidationOwnerCapacity,
        CheckpointFormatRejection::RecordValidationRequest,
        CheckpointFormatRejection::RecoveryCannotRetainANativeCapacityCall,
        CheckpointFormatRejection::RecoveryFamilyOrOutputContinuation,
        CheckpointFormatRejection::RecoveryMixedRoutes,
        CheckpointFormatRejection::RecoveryUnauthenticatedProgression,
        CheckpointFormatRejection::SavedRecordKind,
        CheckpointFormatRejection::SignatureParametersOnAnotherFamily,
    ];
    for value in cases {
        let category: RejectionReason = value.into();
        assert!(matches!(category, RejectionReason::CheckpointFormat(actual) if actual == value));
        let error = Error::Rejected(category);
        assert_eq!(error.clone(), error);
        assert!(
            matches!(&error, Error::Rejected(RejectionReason::CheckpointFormat(actual)) if *actual == value)
        );
        assert!(!value.to_string().is_empty());
        assert!(!category.to_string().is_empty());
        assert!(!error.to_string().is_empty());
        assert!(!format!("{value:?}").is_empty());
    }
}
