//! Public ObjectReferencesRejection values retain identity through category conversion.
use fe11::{Error, ObjectReferencesRejection, RejectionReason};

#[test]
fn variants_preserve_category_and_payload() {
    let cases = [
        ObjectReferencesRejection::CGetObjectSizeUnavailable,
        ObjectReferencesRejection::RsaObservedPublicationAbsent,
        ObjectReferencesRejection::RsaPrivateEvidenceAbsent,
        ObjectReferencesRejection::RsaReadmissionStorageSize,
        ObjectReferencesRejection::RsaReferencePreparationAbsent,
        ObjectReferencesRejection::RsaReferenceQuotaTransferred,
        ObjectReferencesRejection::DestinationAggregateAccounting,
        ObjectReferencesRejection::DestructionAlreadyDispatched,
        ObjectReferencesRejection::DestructionDiagnosticAlreadyConsumed,
        ObjectReferencesRejection::DestructionObservationAbsent,
        ObjectReferencesRejection::DestructionOwnerAbsent,
        ObjectReferencesRejection::DestructionPossessionAbsent,
        ObjectReferencesRejection::DestructionPreparationAccounting,
        ObjectReferencesRejection::DestructionResourceNeedAbsent,
        ObjectReferencesRejection::DestructionStorageSize,
        ObjectReferencesRejection::DiscoveryActivityAlreadyBound,
        ObjectReferencesRejection::DiscoveryIdentityAlreadyShared,
        ObjectReferencesRejection::DiscoveryIdentityMismatch,
        ObjectReferencesRejection::ForeignDestructionResource,
        ObjectReferencesRejection::ForeignNativeObject,
        ObjectReferencesRejection::ForeignOrStaleManagedObject,
        ObjectReferencesRejection::ForeignOrStaleNativeObject,
        ObjectReferencesRejection::InvalidAdmittedHandle,
        ObjectReferencesRejection::InvalidReturnedNativeHandle,
        ObjectReferencesRejection::InventorySortCapacity,
        ObjectReferencesRejection::KeyEvidencePreparationAbsent,
        ObjectReferencesRejection::KeyPublicationAbsent,
        ObjectReferencesRejection::KeyReadmissionCandidateKind,
        ObjectReferencesRejection::KeyReadmissionCompletionPhase,
        ObjectReferencesRejection::KeyReadmissionContinuationChanged,
        ObjectReferencesRejection::KeyReadmissionIncomplete,
        ObjectReferencesRejection::KeyReadmissionNeedAbsent,
        ObjectReferencesRejection::KeyReadmissionOwnerAbsent,
        ObjectReferencesRejection::KeyReadmissionPossessionAbsent,
        ObjectReferencesRejection::KeyReadmissionStopped,
        ObjectReferencesRejection::KeyReadmissionStorageSize,
        ObjectReferencesRejection::KeyReferencePreparationAbsent,
        ObjectReferencesRejection::KeyReferenceQuotaTransferred,
        ObjectReferencesRejection::KeyTypeWidth,
        ObjectReferencesRejection::NativeCreationAlreadyPublished,
        ObjectReferencesRejection::NativeCreationNotPublished,
        ObjectReferencesRejection::NativeIdentityActivityAlreadyBound,
        ObjectReferencesRejection::NativeIdentityNotPublished,
        ObjectReferencesRejection::NativeIdentityPreparationAlreadyShared,
        ObjectReferencesRejection::NativeIdentityPreparationMismatch,
        ObjectReferencesRejection::ObjectObservationLifetimeChanged,
        ObjectReferencesRejection::ObjectSizeAggregateAccountingOverflow,
        ObjectReferencesRejection::ObjectSizeMetadataAccountingOverflow,
        ObjectReferencesRejection::ObservationNativeHandleChanged,
        ObjectReferencesRejection::PublicFingerprintCandidateKind,
        ObjectReferencesRejection::PublicFingerprintCompletionPhase,
        ObjectReferencesRejection::PublicFingerprintContentPhase,
        ObjectReferencesRejection::PublicFingerprintContinuationChanged,
        ObjectReferencesRejection::PublicFingerprintIncomplete,
        ObjectReferencesRejection::PublicFingerprintNeedAbsent,
        ObjectReferencesRejection::PublicFingerprintOwnerAbsent,
        ObjectReferencesRejection::PublicFingerprintPossessionAbsent,
        ObjectReferencesRejection::PublicFingerprintSearchPhase,
        ObjectReferencesRejection::PublicFingerprintStopped,
        ObjectReferencesRejection::PublicFingerprintStorageSize,
        ObjectReferencesRejection::PublicKeyEvidenceAbsent,
        ObjectReferencesRejection::ReadmissionSelectionAbsent,
        ObjectReferencesRejection::ReferenceCandidateKind,
        ObjectReferencesRejection::ReferenceCardinalityWidth,
        ObjectReferencesRejection::ReferenceCompletionPhase,
        ObjectReferencesRejection::ReferenceContentPhase,
        ObjectReferencesRejection::ReferenceContinuationChanged,
        ObjectReferencesRejection::ReferenceDiagnosticStorageSize,
        ObjectReferencesRejection::ReferenceFingerprintPhase,
        ObjectReferencesRejection::ReferenceFingerprintSelection,
        ObjectReferencesRejection::ReferenceIncomplete,
        ObjectReferencesRejection::ReferenceMetadataAllocation,
        ObjectReferencesRejection::ReferenceMetadataPhase,
        ObjectReferencesRejection::ReferenceMetadataSize,
        ObjectReferencesRejection::ReferenceObservationRequiresPreparedOwner,
        ObjectReferencesRejection::ReferenceObservationStopped,
        ObjectReferencesRejection::ReferenceOwnerAbsent,
        ObjectReferencesRejection::ReferencePossessionAbsent,
        ObjectReferencesRejection::ReferencePreparationAlreadyBound,
        ObjectReferencesRejection::ReferencePreparationAlreadyConsumed,
        ObjectReferencesRejection::ReferencePreparationInvalidated,
        ObjectReferencesRejection::ReferenceResourceNeedAbsent,
        ObjectReferencesRejection::ReferenceSearchPhase,
        ObjectReferencesRejection::ReferenceSearchPreparationAbsent,
        ObjectReferencesRejection::ReferenceSnapshotLength,
        ObjectReferencesRejection::ReferenceSourceChanged,
        ObjectReferencesRejection::ReferenceStorageSize,
        ObjectReferencesRejection::RevocationPreparationAlreadyConsumed,
        ObjectReferencesRejection::RevocationReferenceAllocation,
        ObjectReferencesRejection::RevocationReferenceStorageAccounting,
        ObjectReferencesRejection::RevocationRetentionAccounting,
        ObjectReferencesRejection::RevocationRetentionAllocation,
        ObjectReferencesRejection::RevocationRetentionAlreadyConsumed,
        ObjectReferencesRejection::RevocationSetStorageAccounting,
        ObjectReferencesRejection::SecondRsaSearchPreparationAbsent,
        ObjectReferencesRejection::SecondRsaSelectionPhase,
        ObjectReferencesRejection::SecondSelectionPreparationAbsent,
        ObjectReferencesRejection::SelectionIsNotAStorageRequest,
        ObjectReferencesRejection::SigningEvidenceAbsent,
        ObjectReferencesRejection::SigningReferencePreparationAbsent,
        ObjectReferencesRejection::SigningReferenceQuotaTransferred,
        ObjectReferencesRejection::UnselectedReferenceContent,
    ];
    for value in cases {
        let category: RejectionReason = value.into();
        assert!(matches!(category, RejectionReason::ObjectReferences(actual) if actual == value));
        let error = Error::Rejected(category);
        assert_eq!(error.clone(), error);
        assert!(
            matches!(&error, Error::Rejected(RejectionReason::ObjectReferences(actual)) if *actual == value)
        );
        assert!(!value.to_string().is_empty());
        assert!(!category.to_string().is_empty());
        assert!(!error.to_string().is_empty());
        assert!(!format!("{value:?}").is_empty());
    }
}
