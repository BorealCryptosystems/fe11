//! Public ObjectCreationRejection values retain identity through category conversion.
use fe11::{Error, ObjectCreationRejection, RejectionReason};

#[test]
fn variants_preserve_category_and_payload() {
    let cases = [
        ObjectCreationRejection::KemCallAbsent,
        ObjectCreationRejection::KemCompletionPhase,
        ObjectCreationRejection::KemCompletionUnknown,
        ObjectCreationRejection::KemDispatchPhase,
        ObjectCreationRejection::KemNativeOutcomeAbsent,
        ObjectCreationRejection::KemObservationStorageSize,
        ObjectCreationRejection::KemOutputEvidenceAbsent,
        ObjectCreationRejection::MlKemNativeCiphertextLength,
        ObjectCreationRejection::TlsOutputKind,
        ObjectCreationRejection::AttributeMutationActivityChanged,
        ObjectCreationRejection::AttributeMutationActivityChangedAfterReturn,
        ObjectCreationRejection::AttributeMutationActivityUnavailable,
        ObjectCreationRejection::AttributeMutationActivityUnavailableAfterReturn,
        ObjectCreationRejection::AttributeMutationCreatorChanged,
        ObjectCreationRejection::AttributeMutationCreatorChangedAfterReturn,
        ObjectCreationRejection::AttributeMutationCreatorLostAfterReturn,
        ObjectCreationRejection::AttributeMutationCreatorUnavailable,
        ObjectCreationRejection::AttributeMutationDestinationReservation,
        ObjectCreationRejection::AttributeMutationMetadataOwner,
        ObjectCreationRejection::AttributeMutationModuleReleased,
        ObjectCreationRejection::AttributeMutationPreparedOriginOwner,
        ObjectCreationRejection::ConflictingCreationClasses,
        ObjectCreationRejection::CoordinationCopyAllocation,
        ObjectCreationRejection::CopyDiagnosticsAbsent,
        ObjectCreationRejection::CopySourceAbsent,
        ObjectCreationRejection::CreatedObjectAbsent,
        ObjectCreationRejection::CreatedObjectHandles,
        ObjectCreationRejection::CreatedObjectRecordChanged,
        ObjectCreationRejection::CreatedObjectRecordMissing,
        ObjectCreationRejection::CreatingSessionClosed,
        ObjectCreationRejection::CreatingSessionClosingOrUncertain,
        ObjectCreationRejection::CreatingSessionReleased,
        ObjectCreationRejection::CreationActivityAllocation,
        ObjectCreationRejection::CreationAdmissionPhase,
        ObjectCreationRejection::CreationAdmissionPreparationAbsent,
        ObjectCreationRejection::CreationAggregateAccounting,
        ObjectCreationRejection::CreationCandidateKind,
        ObjectCreationRejection::CreationClassAbiRepresentation,
        ObjectCreationRejection::CreationClassIsRequired,
        ObjectCreationRejection::CreationCleanupSize,
        ObjectCreationRejection::CreationCompletionPhase,
        ObjectCreationRejection::CreationContinuationChanged,
        ObjectCreationRejection::CreationDestination,
        ObjectCreationRejection::CreationDestinationPhase,
        ObjectCreationRejection::CreationDiagnosticAbsent,
        ObjectCreationRejection::CreationMetadataPhase,
        ObjectCreationRejection::CreationMetadataStorageAccounting,
        ObjectCreationRejection::CreationNativeLifetimeAbsent,
        ObjectCreationRejection::CreationOriginUnavailableForCleanup,
        ObjectCreationRejection::CreationOwnerAbsent,
        ObjectCreationRejection::CreationOwnerChangedBeforeCleanup,
        ObjectCreationRejection::CreationOwnerUnavailable,
        ObjectCreationRejection::CreationPossessionAbsent,
        ObjectCreationRejection::CreationPreparationAlreadyConsumed,
        ObjectCreationRejection::CreationPublicationAccounting,
        ObjectCreationRejection::CreationPublicationCapacity,
        ObjectCreationRejection::CreationPublicationCapacityChanged,
        ObjectCreationRejection::CreationPublicationQuotaAbsent,
        ObjectCreationRejection::CreationPublicationQuotaTransferred,
        ObjectCreationRejection::CreationPublicationSlotExhausted,
        ObjectCreationRejection::CreationRecordChanged,
        ObjectCreationRejection::CreationRecordMissing,
        ObjectCreationRejection::CreationResourceNeedAbsent,
        ObjectCreationRejection::CreationSessionReleased,
        ObjectCreationRejection::CreationStorageSize,
        ObjectCreationRejection::ForeignCreationReservation,
        ObjectCreationRejection::ForeignForgottenResource,
        ObjectCreationRejection::GeneratedObjectAbsent,
        ObjectCreationRejection::GeneratedOutputKind,
        ObjectCreationRejection::GeneratedPrivateObjectAbsent,
        ObjectCreationRejection::GeneratedPublicObjectAbsent,
        ObjectCreationRejection::GroupCreationScope,
        ObjectCreationRejection::KeyGenerationStorageAccounting,
        ObjectCreationRejection::KeyMaterialObservationLayout,
        ObjectCreationRejection::KeyMaterialRequestAccounting,
        ObjectCreationRejection::KeyMaterialResultAccounting,
        ObjectCreationRejection::KeyMaterialResultAllocation,
        ObjectCreationRejection::KeyPairGenerationStorageAccounting,
        ObjectCreationRejection::LogoutAliasSnapshotAllocation,
        ObjectCreationRejection::LogoutAliasSnapshotSize,
        ObjectCreationRejection::MutationModuleReleased,
        ObjectCreationRejection::NativeCreationAggregateAccounting,
        ObjectCreationRejection::NativeCreationStorageAccounting,
        ObjectCreationRejection::ObjectAlreadyCreated,
        ObjectCreationRejection::ObjectCreationIncomplete,
        ObjectCreationRejection::ObjectCreationStopped,
        ObjectCreationRejection::ObjectCreatorAllocation,
        ObjectCreationRejection::ObjectCreatorAlreadyRecorded,
        ObjectCreationRejection::PairAuxiliaryOutputOwner,
        ObjectCreationRejection::PairParameterPreparationChanged,
        ObjectCreationRejection::PrivateCreationObservationStorageSize,
        ObjectCreationRejection::PrivateImportEvidenceAbsent,
        ObjectCreationRejection::PrivateObservationStorageSize,
        ObjectCreationRejection::PublicDerPublicationPairing,
        ObjectCreationRejection::PublicCreationStorageSize,
        ObjectCreationRejection::PublicImportMechanismReportAbsent,
        ObjectCreationRejection::RenameCreatorChanged,
        ObjectCreationRejection::RenameCreatorUnavailable,
        ObjectCreationRejection::RenameDestinationReservation,
        ObjectCreationRejection::RenameModuleReleased,
        ObjectCreationRejection::RestorationEvidenceAbsent,
        ObjectCreationRejection::RestorationObservationStorageSize,
        ObjectCreationRejection::SigningImportEvidenceAbsent,
        ObjectCreationRejection::UnexpectedKemUnwrap,
        ObjectCreationRejection::UnexpectedNativeKem,
        ObjectCreationRejection::UnexpectedNativeUnwrap,
        ObjectCreationRejection::UnexpectedRestorationKem,
        ObjectCreationRejection::UnexpectedSigningEvidence,
        ObjectCreationRejection::UnwrapCallAbsent,
        ObjectCreationRejection::UnwrapCompletionPhase,
        ObjectCreationRejection::UnwrapCompletionUnknown,
        ObjectCreationRejection::UnwrapDispatchPhase,
    ];
    for value in cases {
        let category: RejectionReason = value.into();
        assert!(matches!(category, RejectionReason::ObjectCreation(actual) if actual == value));
        let error = Error::Rejected(category);
        assert_eq!(error.clone(), error);
        assert!(
            matches!(&error, Error::Rejected(RejectionReason::ObjectCreation(actual)) if *actual == value)
        );
        assert!(!value.to_string().is_empty());
        assert!(!category.to_string().is_empty());
        assert!(!error.to_string().is_empty());
        assert!(!format!("{value:?}").is_empty());
    }
}
