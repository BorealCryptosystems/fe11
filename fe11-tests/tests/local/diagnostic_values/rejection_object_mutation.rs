//! Public ObjectMutationRejection values retain identity through category conversion.
use fe11::{Error, ObjectMutationRejection, RejectionReason};

#[test]
fn variants_preserve_category_and_payload() {
    let cases = [
        ObjectMutationRejection::CSetAttributeValueUnavailable,
        ObjectMutationRejection::AttributeMutationAlreadyDispatched,
        ObjectMutationRejection::AttributeMutationCandidateKind,
        ObjectMutationRejection::AttributeMutationCompletionPhase,
        ObjectMutationRejection::AttributeMutationContinuationChanged,
        ObjectMutationRejection::AttributeMutationIncomplete,
        ObjectMutationRejection::AttributeMutationInputChanged,
        ObjectMutationRejection::AttributeMutationOwnerAbsent,
        ObjectMutationRejection::AttributeMutationPossessionAbsent,
        ObjectMutationRejection::AttributeMutationPreparationAccounting,
        ObjectMutationRejection::AttributeMutationResourceNeedAbsent,
        ObjectMutationRejection::AttributeMutationStopped,
        ObjectMutationRejection::AttributeMutationStorageSize,
        ObjectMutationRejection::CertificateDer,
        ObjectMutationRejection::CertificateCategoryNativeWidth,
        ObjectMutationRejection::CertificateEncoding,
        ObjectMutationRejection::CertificateSize,
        ObjectMutationRejection::ContentClassAbsent,
        ObjectMutationRejection::ContentCreationStorageSize,
        ObjectMutationRejection::DataTypeOid,
        ObjectMutationRejection::DataTypeOidEncoding,
        ObjectMutationRejection::DestinationAllocation,
        ObjectMutationRejection::DestinationClassExceedsNativeWidth,
        ObjectMutationRejection::DestinationClassTupleShape,
        ObjectMutationRejection::DestinationCount,
        ObjectMutationRejection::DestinationOutsideReservation,
        ObjectMutationRejection::DestinationPreparationAllocation,
        ObjectMutationRejection::DestinationProbeAlreadyConsumed,
        ObjectMutationRejection::DestinationQuotaExceeded,
        ObjectMutationRejection::DuplicateSelection,
        ObjectMutationRejection::DynamicReaderAggregateAccounting,
        ObjectMutationRejection::ForeignInventoryPreparation,
        ObjectMutationRejection::ForeignOperationDestination,
        ObjectMutationRejection::ForeignOperationReservation,
        ObjectMutationRejection::ForeignOperationSelection,
        ObjectMutationRejection::ForeignPreparedSelection,
        ObjectMutationRejection::GenerationCoordinationAccounting,
        ObjectMutationRejection::GenerationDestinationAccounting,
        ObjectMutationRejection::GenerationProbeAlreadyConsumed,
        ObjectMutationRejection::InvalidResourceActivityHandle,
        ObjectMutationRejection::InventoryAllocation,
        ObjectMutationRejection::InventoryCount,
        ObjectMutationRejection::InventoryOwnerAllocation,
        ObjectMutationRejection::InventoryOwnerSize,
        ObjectMutationRejection::InventoryPreparationAlreadyPublished,
        ObjectMutationRejection::InventoryPreparationAlreadyShared,
        ObjectMutationRejection::IssuerEncoding,
        ObjectMutationRejection::KeySelectionClass,
        ObjectMutationRejection::LabelAdmissionPhase,
        ObjectMutationRejection::LabelAdmissionPreparationAbsent,
        ObjectMutationRejection::LabelAlreadyDispatched,
        ObjectMutationRejection::LabelCandidateKind,
        ObjectMutationRejection::LabelClassPreparationAbsent,
        ObjectMutationRejection::LabelContinuationChanged,
        ObjectMutationRejection::LabelDestinationPhase,
        ObjectMutationRejection::LabelDestinationPreparationAbsent,
        ObjectMutationRejection::LabelMetadataPhase,
        ObjectMutationRejection::LabelMutationCompletionPhase,
        ObjectMutationRejection::LabelMutationIncomplete,
        ObjectMutationRejection::LabelMutationStopped,
        ObjectMutationRejection::LabelMutationStorageSize,
        ObjectMutationRejection::LabelOwnerAbsent,
        ObjectMutationRejection::LabelPossessionAbsent,
        ObjectMutationRejection::LabelPublicationQuotaTransferred,
        ObjectMutationRejection::LabelReferencePhase,
        ObjectMutationRejection::LabelResourceNeedAbsent,
        ObjectMutationRejection::ManagedSelectionAllocation,
        ObjectMutationRejection::MutationContentPhase,
        ObjectMutationRejection::MutationDestinationPhase,
        ObjectMutationRejection::MutationFingerprintPhase,
        ObjectMutationRejection::MutationFingerprintSelection,
        ObjectMutationRejection::MutationMetadataPhase,
        ObjectMutationRejection::MutationObservationFieldCount,
        ObjectMutationRejection::MutationObservationRequiresPreparedOwner,
        ObjectMutationRejection::MutationOwnerAbsent,
        ObjectMutationRejection::MutationReferencePhase,
        ObjectMutationRejection::MutationSourcePreparationAbsent,
        ObjectMutationRejection::NoncanonicalCertificate,
        ObjectMutationRejection::NoncanonicalDataType,
        ObjectMutationRejection::ObjectDestinationReserved,
        ObjectMutationRejection::OperationActivityAllocation,
        ObjectMutationRejection::OperationDestinationAllocation,
        ObjectMutationRejection::OperationDestinationChanged,
        ObjectMutationRejection::OperationDestinationCount,
        ObjectMutationRejection::OperationRetentionAbsent,
        ObjectMutationRejection::OperationSelectionAllocation,
        ObjectMutationRejection::PairSelectionAllocation,
        ObjectMutationRejection::PublicPairSelectionPreparation,
        ObjectMutationRejection::RequestedDestinationOperandUnavailable,
        ObjectMutationRejection::ReservationActivityAllocation,
        ObjectMutationRejection::ReservationActivityStorageSize,
        ObjectMutationRejection::ReservationActivityVectorSize,
        ObjectMutationRejection::ReservationDestinationAllocation,
        ObjectMutationRejection::ReservationPreparationSize,
        ObjectMutationRejection::ReservationVectorSize,
        ObjectMutationRejection::ResourceActivityAllocation,
        ObjectMutationRejection::ResourcePublicationCapacity,
        ObjectMutationRejection::SelectionAllocation,
        ObjectMutationRejection::SelectionCount,
        ObjectMutationRejection::SerialEncoding,
        ObjectMutationRejection::SubjectEncoding,
        ObjectMutationRejection::UnknownClassSelectionContract,
        ObjectMutationRejection::UnobservedDestinationClass,
        ObjectMutationRejection::UnselectedMutationContent,
    ];
    for value in cases {
        let category: RejectionReason = value.into();
        assert!(matches!(category, RejectionReason::ObjectMutation(actual) if actual == value));
        let error = Error::Rejected(category);
        assert_eq!(error.clone(), error);
        assert!(
            matches!(&error, Error::Rejected(RejectionReason::ObjectMutation(actual)) if *actual == value)
        );
        assert!(!value.to_string().is_empty());
        assert!(!category.to_string().is_empty());
        assert!(!error.to_string().is_empty());
        assert!(!format!("{value:?}").is_empty());
    }
}
