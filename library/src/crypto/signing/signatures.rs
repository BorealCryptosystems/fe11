//! Expose classical key-pair generation, discovery and signing facades.
//! Selected mechanisms and contextual authentication are forwarded explicitly.

use super::*;

impl Session {
    /// Generate native keys with the exact usage, storage and mechanism requests.
    /// No possession proof or implicit signature is performed. Created references
    /// survive an optional observation failure in the separate creation result.
    pub fn generate_classical_key_pair(
        &self,
        spec: ClassicalKeySpec,

        public_mechanisms: crate::MechanismObservationPlan,
    ) -> Result<crate::CreatedObjects<ClassicalKeyPair>> {
        self.generate_classical_key_pair_selected(spec, public_mechanisms)
    }

    pub(super) fn generate_classical_key_pair_selected(
        &self,
        spec: ClassicalKeySpec,

        public_mechanisms: crate::MechanismObservationPlan,
    ) -> Result<crate::CreatedObjects<ClassicalKeyPair>> {
        let mut diagnostics = crate::advanced::PollDiagnostics::default();
        let prepared = crate::crypto::ClassicalPairPlan::generating(
            spec,
            public_mechanisms,
            self.inner.crypto_options.edwards,
            0,
        )?;
        crate::advanced::classical_pair_synchronous(self, prepared, true, &mut diagnostics)
    }

    /// Select existing public and private objects using the explicit lookup plans.
    /// The supplied canonical SPKI describes the requested view; no private/public
    /// correspondence or possession is attested. No key, signature or challenge
    /// is generated by this lookup.
    pub fn find_classical_key_pair(
        &self,
        id: &[u8],
        expected_spki: &[u8],
        profiles: &[SignatureProfile],

        mechanisms: crate::MechanismObservationPlan,
        public_mechanisms: crate::MechanismObservationPlan,
        public_admission: crate::ObjectAdmission,
        private_admission: crate::ObjectAdmission,
    ) -> Result<ClassicalKeyPair> {
        self.find_classical_key_pair_selected(
            id,
            expected_spki,
            profiles,
            mechanisms,
            public_mechanisms,
            public_admission,
            private_admission,
        )
    }

    pub(super) fn find_classical_key_pair_selected(
        &self,
        id: &[u8],
        expected_spki: &[u8],
        profiles: &[SignatureProfile],

        mechanisms: crate::MechanismObservationPlan,
        public_mechanisms: crate::MechanismObservationPlan,
        public_admission: crate::ObjectAdmission,
        private_admission: crate::ObjectAdmission,
    ) -> Result<ClassicalKeyPair> {
        let mut diagnostics = crate::advanced::PollDiagnostics::default();
        let prepared = crate::crypto::ClassicalPairPlan::selected(
            id,
            expected_spki,
            profiles,
            mechanisms,
            public_mechanisms,
            public_admission,
            private_admission,
            self.inner.crypto_options.edwards,
        )?;
        crate::advanced::classical_pair_synchronous(self, prepared, false, &mut diagnostics)
            .and_then(|outcome| outcome.observation)
    }

    /// Sign the exact message under a validated private reference. There is no
    /// caller-prepared ECDSA digest entry, nor raw private handle conversion.
    pub fn sign_classical(
        &self,
        key: &SigningKey,
        request: SigningRequest,
        message: &[u8],
        limits: InputLimits,
    ) -> Result<ClassicalSignature> {
        let mut invocation_diagnostics = crate::crypto::ClassicalDiagnostics::default();
        let diagnostics = &mut invocation_diagnostics;
        self.sign_classical_parts(key.view(), request, &[message], false, limits, diagnostics)
    }

    /// Sign bounded available pieces using actual native Update/Final in
    /// combined or native-digest mode; never concatenate them silently.
    pub fn sign_classical_multipart(
        &self,
        key: &SigningKey,
        request: SigningRequest,
        parts: &[&[u8]],
        limits: InputLimits,
    ) -> Result<ClassicalSignature> {
        let mut invocation_diagnostics = crate::crypto::ClassicalDiagnostics::default();
        let diagnostics = &mut invocation_diagnostics;
        self.sign_classical_parts(key.view(), request, parts, true, limits, diagnostics)
    }

    /// Sign one message with an explicit contextual login after SignInit.
    /// A refusal retains the initialized operation until successful session
    /// closure, as in Session::sign_pss_with_context; credentials are single-use.
    pub fn sign_classical_with_context(
        &self,
        key: &SigningKey,
        request: SigningRequest,
        message: &[u8],
        limits: InputLimits,
        authentication: crate::ContextAuthentication,
    ) -> Result<ClassicalSignature> {
        let mut invocation_diagnostics = crate::crypto::ClassicalDiagnostics::default();
        let diagnostics = &mut invocation_diagnostics;
        self.sign_classical_parts_with_context(
            key.view(),
            request,
            &[message],
            false,
            limits,
            Some(authentication),
            diagnostics,
        )
    }

    /// Authenticate once after SignInit and before the first SignUpdate.
    /// A preceding native digest operation receives no contextual login.
    pub fn sign_classical_multipart_with_context(
        &self,
        key: &SigningKey,
        request: SigningRequest,
        parts: &[&[u8]],
        limits: InputLimits,
        authentication: crate::ContextAuthentication,
    ) -> Result<ClassicalSignature> {
        let mut invocation_diagnostics = crate::crypto::ClassicalDiagnostics::default();
        let diagnostics = &mut invocation_diagnostics;
        self.sign_classical_parts_with_context(
            key.view(),
            request,
            parts,
            true,
            limits,
            Some(authentication),
            diagnostics,
        )
    }

    pub(super) fn sign_classical_parts(
        &self,
        key: SigningKeyView<'_>,
        request: SigningRequest,
        parts: &[&[u8]],
        multipart: bool,
        limits: InputLimits,
        diagnostics: &mut crate::crypto::ClassicalDiagnostics,
    ) -> Result<ClassicalSignature> {
        self.sign_classical_parts_with_context(
            key,
            request,
            parts,
            multipart,
            limits,
            None,
            diagnostics,
        )
    }

    // Without a contextual request, no login is performed. An explicit request
    // instead joins permissions, witnesses and native frame in one reservation.
    pub(super) fn classical_context_access(
        &self,
        key: &ManagedObjectRef,
        mut authentication: Option<crate::ContextAuthentication>,
        digest_plan: Option<&super::super::native_digest::Plan>,
        signature_plan: &super::super::native_signature::storage::Plan,
        prehash_plan: &super::super::native_signature::prehash::Plan,
        parts: &[&[u8]],
        retained_digest: Option<&super::super::PreparedDigest>,
    ) -> Result<(
        Option<super::super::native_digest::Prepared>,
        super::super::native_signature::storage::Storage,
        super::super::native_signature::prehash::Storage,
        crate::session::SessionAccess<'_>,
        Option<crate::session::PreparedContextLogin<'_>>,
    )> {
        let prepared_authentication;
        let epoch = self.snapshot.authentication_stamp();
        let progress = match retained_digest {
            Some(digest) => crate::session::AdmissionProgress::default()
                .retaining(digest.retained_bytes(&self.inner.symmetric_budget)?)?,
            None => crate::session::AdmissionProgress::default(),
        };
        let mut authentication_plan =
            crate::session::ContextLoginPlan::at_epoch(self, authentication.as_ref(), epoch)?;
        let (
            (((prepared_digest, prehash_storage), signature_storage), mut authentication_storage),
            s,
        ) = self.prepare_with_roles_prepaid_at_epoch(
            [(Some(key), crate::session::activity::AccessMode::Read)],
            authentication.is_some(),
            epoch,
            &progress,
            |overhead| {
                authentication_plan.prepare(self, overhead, |bytes| {
                    signature_plan.prepare(bytes, |bytes| {
                        prehash_plan.prepare(parts, bytes, |bytes| match digest_plan {
                            Some(plan) => plan
                                .prepare(self, bytes, &progress, epoch)
                                .map(|(call, credit)| (Some(call), credit)),
                            None => crate::advanced::reserve_preparation_at_epoch(
                                self, bytes, &progress, epoch,
                            )
                            .map(|credit| (None, credit)),
                        })
                    })
                })
            },
        )?;
        prepared_authentication = crate::session::PreparedContextLogin::from_prepared(
            self,
            &s,
            &mut authentication,
            &mut authentication_storage,
        )?;
        Ok((
            prepared_digest,
            signature_storage,
            prehash_storage,
            s,
            prepared_authentication,
        ))
    }

    pub(super) fn sign_classical_parts_with_context(
        &self,
        key: SigningKeyView<'_>,
        request: SigningRequest,
        parts: &[&[u8]],
        multipart: bool,
        limits: InputLimits,
        authentication: Option<crate::ContextAuthentication>,
        diagnostics: &mut crate::crypto::ClassicalDiagnostics,
    ) -> Result<ClassicalSignature> {
        limits.validate(self.inner.crypto_options.limits, parts)?;

        key.algorithm.validate_profiles(&[request.profile()])?;
        let digest_plan = match request.hash_request() {
            Some((hash, HashExecution::Pkcs11DigestThenPrimitive)) => {
                Some(super::super::native_digest::Plan::new(
                    &super::super::NativeHash::Modern(hash),
                    parts,
                    multipart,
                )?)
            }
            _ => None,
        };
        let input_length = match request.hash_request() {
            Some((
                hash,
                HashExecution::RustSoftware | HashExecution::Pkcs11DigestThenPrimitive,
            )) => {
                if matches!(request, SigningRequest::RsaPkcs1 { .. }) {
                    super::super::rsa::digest_info_length(hash)?
                } else {
                    hash.output_length()
                }
            }
            _ => parts.iter().map(|part| part.len()).max().unwrap_or(0),
        };
        let signature_plan = super::super::native_signature::storage::Plan::new(
            input_length,
            key.algorithm.signature_width(),
        )?;
        let prehash_plan = super::super::native_signature::prehash::Plan {
            software: request
                .hash_request()
                .and_then(|(hash, route)| (route == HashExecution::RustSoftware).then_some(hash)),
            encoded_length: request.hash_request().and_then(|(_, route)| {
                (route != HashExecution::Pkcs11Combined).then_some(input_length)
            }),
        };
        let (mut prepared_digest, signature_storage, mut prehash_storage, s, mut authentication) =
            self.classical_context_access(
                key.managed,
                authentication,
                digest_plan.as_ref(),
                &signature_plan,
                &prehash_plan,
                parts,
                None,
            )?;
        let result = (|| {
            if let Some(digest) = prehash_storage.software.as_ref() {
                request.encode_digest_into(
                    digest,
                    prehash_storage.encoded.as_mut().expect("prepared encoding"),
                )?;
            }
            let object = self.managed_handle(&s, key.managed)?;
            let access = key.managed.identity.access;
            request.mechanism()?;

            let native_multipart = multipart
                && request.hash_request().map_or(true, |(_, execution)| {
                    execution == HashExecution::Pkcs11Combined
                });
            let missing_sign = if native_multipart {
                s.native.table.C_SignUpdate.is_none() || s.native.table.C_SignFinal.is_none()
            } else {
                s.native.table.C_Sign.is_none()
            };
            if s.native.table.C_SignInit.is_none() || missing_sign {
                return Err(Error::Rejected(
                    crate::RejectionReason::ClassicalSignatures(
                        crate::ClassicalSignaturesRejection::SigningFunctionsUnavailable,
                    ),
                ));
            }
            let bytes = match request.hash_request() {
                Some((hash, execution)) => match execution {
                    HashExecution::RustSoftware => self.hashed_sign_native_with_context(
                        &s,
                        object,
                        request,
                        key.algorithm,
                        &[prehash_storage
                            .encoded
                            .as_ref()
                            .expect("software digest encoding")
                            .as_slice()],
                        false,
                        access,
                        authentication.as_mut(),
                        signature_storage,
                        diagnostics,
                    )?,
                    HashExecution::Pkcs11Combined => self.hashed_sign_native_with_context(
                        &s,
                        object,
                        request,
                        key.algorithm,
                        parts,
                        multipart,
                        access,
                        authentication.as_mut(),
                        signature_storage,
                        diagnostics,
                    )?,
                    HashExecution::Pkcs11DigestThenPrimitive => {
                        let digest = self.digest_guarded(
                            &s,
                            hash,
                            parts,
                            multipart,
                            prepared_digest.take().expect("native prehash prepared"),
                            diagnostics,
                        )?;
                        let mut encoded = prehash_storage
                            .encoded
                            .take()
                            .expect("native digest encoding");
                        request.encode_digest_into(&digest, &mut encoded)?;
                        self.hashed_sign_native_with_context(
                            &s,
                            object,
                            request,
                            key.algorithm,
                            &[encoded.as_slice()],
                            false,
                            access,
                            authentication.as_mut(),
                            signature_storage,
                            diagnostics,
                        )?
                    }
                },
                None => self.eddsa_sign_native_with_context(
                    &s,
                    object,
                    key.algorithm == ClassicalKeyAlgorithm::Ed448,
                    request.signature_parameters()?,
                    parts,
                    multipart,
                    access,
                    authentication.as_mut(),
                    signature_storage,
                    diagnostics,
                )?,
            };
            Ok(ClassicalSignature {
                bytes,
                algorithm: key.algorithm,
                profile: request.profile(),
                provenance: request.hash_request().map_or(
                    match request {
                        SigningRequest::EdDsa(p) if p.prehash() => {
                            SignatureHashProvenance::NativeEdwardsPrehash
                        }
                        _ => SignatureHashProvenance::PureEdwards,
                    },
                    |(_, e)| SignatureHashProvenance::Executed(e),
                ),
            })
        })();
        diagnostics.authentication = authentication.map(|value| value.into_diagnostics());
        result
    }

    /// RSA-only caller-prepared digest. DigestInfo is constructed here for
    /// PKCS1v1.5; PSS parameters and digest identity must match exactly. This
    /// entry cannot perform ECDSA or accept caller-provided raw RSA blocks.
    pub fn sign_rsa_digest(
        &self,
        key: &SigningKey,
        rsa_profile: RsaSignatureProfile,
        digest: &super::super::PreparedDigest,
    ) -> Result<ClassicalSignature> {
        let mut invocation_diagnostics = crate::crypto::ClassicalDiagnostics::default();
        let diagnostics = &mut invocation_diagnostics;
        self.sign_rsa_digest_view(key.view(), rsa_profile, digest, diagnostics)
    }

    /// Sign an explicitly caller-prepared RSA digest after one contextual login.
    /// Digest identity/encoding and PSS parameters retain sign_rsa_digest checks.
    pub fn sign_rsa_digest_with_context(
        &self,
        key: &SigningKey,
        profile: RsaSignatureProfile,
        digest: &super::super::PreparedDigest,
        authentication: crate::ContextAuthentication,
    ) -> Result<ClassicalSignature> {
        let mut invocation_diagnostics = crate::crypto::ClassicalDiagnostics::default();
        let diagnostics = &mut invocation_diagnostics;
        self.sign_rsa_digest_view_with_context(
            key.view(),
            profile,
            digest,
            Some(authentication),
            diagnostics,
        )
    }

    pub(super) fn sign_rsa_digest_view(
        &self,
        key: SigningKeyView<'_>,
        rsa_profile: RsaSignatureProfile,
        digest: &super::super::PreparedDigest,
        diagnostics: &mut crate::crypto::ClassicalDiagnostics,
    ) -> Result<ClassicalSignature> {
        self.sign_rsa_digest_view_with_context(key, rsa_profile, digest, None, diagnostics)
    }

    pub(super) fn sign_rsa_digest_view_with_context(
        &self,
        key: SigningKeyView<'_>,
        rsa_profile: RsaSignatureProfile,
        digest: &super::super::PreparedDigest,
        authentication: Option<crate::ContextAuthentication>,
        diagnostics: &mut crate::crypto::ClassicalDiagnostics,
    ) -> Result<ClassicalSignature> {
        let profile = match rsa_profile {
            RsaSignatureProfile::Pkcs1(hash) => SignatureProfile::RsaPkcs1(hash),
            RsaSignatureProfile::Pss(parameters) => SignatureProfile::RsaPss(parameters),
        };

        if !matches!(key.algorithm, ClassicalKeyAlgorithm::Rsa { .. }) {
            return Err(Error::Rejected(
                crate::RejectionReason::ClassicalSignatures(
                    crate::ClassicalSignaturesRejection::RsaPreparedSigningPermission,
                ),
            ));
        }
        // The route below selects the primitive only; provenance is CallerPrepared.
        let request = match profile {
            SignatureProfile::RsaPkcs1(hash) if hash == digest.algorithm => {
                SigningRequest::RsaPkcs1 {
                    hash,
                    execution: HashExecution::RustSoftware,
                }
            }
            SignatureProfile::RsaPss(parameters) if parameters.hash == digest.algorithm => {
                SigningRequest::RsaPss {
                    parameters,
                    execution: HashExecution::RustSoftware,
                }
            }
            _ => {
                return Err(Error::Rejected(
                    crate::RejectionReason::ClassicalSignatures(
                        crate::ClassicalSignaturesRejection::RsaPreparedDigestProfile,
                    ),
                ))
            }
        };
        request.mechanism()?;
        let input_length = if matches!(request, SigningRequest::RsaPkcs1 { .. }) {
            super::super::rsa::digest_info_length(digest.algorithm)?
        } else {
            digest.as_bytes().len()
        };
        let signature_plan = super::super::native_signature::storage::Plan::new(
            input_length,
            key.algorithm.signature_width(),
        )?;
        let prehash_plan = super::super::native_signature::prehash::Plan {
            software: None,
            encoded_length: Some(input_length),
        };
        let (_, signature_storage, mut prehash_storage, s, mut authentication) = self
            .classical_context_access(
                key.managed,
                authentication,
                None,
                &signature_plan,
                &prehash_plan,
                &[],
                Some(digest),
            )?;
        let result = (|| {
            let mut input = prehash_storage
                .encoded
                .take()
                .expect("prepared RSA encoding");
            request.encode_digest_into(digest, &mut input)?;
            let object = self.managed_handle(&s, key.managed)?;

            let bytes = self.hashed_sign_native_with_context(
                &s,
                object,
                request,
                key.algorithm,
                &[input.as_slice()],
                false,
                key.managed.identity.access,
                authentication.as_mut(),
                signature_storage,
                diagnostics,
            )?;
            Ok(ClassicalSignature {
                bytes,
                algorithm: key.algorithm,
                profile,
                provenance: SignatureHashProvenance::CallerPrepared,
            })
        })();
        diagnostics.authentication = authentication.map(|value| value.into_diagnostics());
        result
    }

    // This typed view uses the declared width for output representation. Only
    // its SPKI encoding must agree; no private/public equality is established.
    // Callers needing an uninterpreted native route use NativeObjectRef.
    pub(super) fn validate_signing_public(
        &self,
        der: &[u8],
        algorithm: ClassicalKeyAlgorithm,
    ) -> Result<()> {
        if let ClassicalKeyAlgorithm::Rsa { bits } = algorithm {
            let key = super::super::integer_key::rsa_der(der)?;
            if key.bits != bits {
                return Err(Error::Rejected(
                    crate::RejectionReason::ClassicalSignatures(
                        crate::ClassicalSignaturesRejection::RsaSigningIdentity,
                    ),
                ));
            }
            Ok(())
        } else {
            curve_spki(der).map(|_| ())
        }
    }

    pub(super) fn hashed_sign_native_with_context(
        &self,
        s: &crate::session::SessionAccess<'_>,
        object: CK_OBJECT_HANDLE,
        request: SigningRequest,
        algorithm: ClassicalKeyAlgorithm,
        parts: &[&[u8]],
        multipart: bool,
        access: crate::managed::ObjectAccess,
        authentication: Option<&mut crate::session::PreparedContextLogin<'_>>,
        prepared: super::super::native_signature::storage::Storage,
        diagnostics: &mut crate::crypto::ClassicalDiagnostics,
    ) -> Result<SecretBytes> {
        use super::super::native_signature::{SignatureOutput, SignatureParameters};
        access.check(&self.snapshot)?;
        let result = (|| {
            let encoding = match algorithm {
                ClassicalKeyAlgorithm::Rsa { bits } => {
                    SignatureOutput::ExactLength(bits / 8 + usize::from(bits % 8 != 0))
                }
                ClassicalKeyAlgorithm::Ecdsa(curve) => SignatureOutput::Ecdsa(curve),
                _ => {
                    return Err(Error::Rejected(
                        crate::RejectionReason::ClassicalSignatures(
                            crate::ClassicalSignaturesRejection::HashedSignatureFamily,
                        ),
                    ))
                }
            };
            let parameters = match request.pss()? {
                Some(parameters) => SignatureParameters::pss(parameters),
                None => SignatureParameters::None,
            };
            self.sign_native_frame(
                s,
                object,
                request.mechanism()?,
                parameters,
                encoding,
                parts,
                multipart,
                authentication,
                prepared,
                diagnostics,
            )
        })();
        access.result(self, s, result)
    }
}
